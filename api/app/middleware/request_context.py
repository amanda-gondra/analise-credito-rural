"""Give every request an id and log one line of operational data about it.

The id is generated by the server (a client cannot choose it), stored in
request.state.request_id, returned in the X-Request-ID header and written in
error bodies, so a client report can be matched to a log line.

Logged: id, method, path, status and duration. Not the query string, so filters
typed by visitors (and anything pasted into them) do not reach the logs.
"""

from __future__ import annotations

import logging
import time
import uuid
from typing import Final

from starlette.datastructures import MutableHeaders
from starlette.types import ASGIApp, Message, Receive, Scope, Send

logger = logging.getLogger("rural_credit_api.access")

REQUEST_ID_HEADER: Final = "X-Request-ID"


class RequestContextMiddleware:
    def __init__(self, app: ASGIApp) -> None:
        self.app = app

    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:
        if scope["type"] != "http":
            await self.app(scope, receive, send)
            return

        request_id = uuid.uuid4().hex
        scope.setdefault("state", {})["request_id"] = request_id
        status = 500
        started = time.perf_counter()

        async def send_with_id(message: Message) -> None:
            nonlocal status
            if message["type"] == "http.response.start":
                status = message["status"]
                MutableHeaders(scope=message).append(REQUEST_ID_HEADER, request_id)
            await send(message)

        try:
            await self.app(scope, receive, send_with_id)
        finally:
            logger.info(
                "request_id=%s method=%s path=%s status=%d duration_ms=%.1f",
                request_id,
                scope["method"],
                scope["path"],
                status,
                1000 * (time.perf_counter() - started),
            )
